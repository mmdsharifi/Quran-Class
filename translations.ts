export const translate = (key: keyof typeof TRANSLATIONS['fa'], lang: 'fa' | 'en', params?: Record<string, string | number>) => {
  let val = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['fa']?.[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      val = val.replace(`{${k}}`, String(v));
    });
  }
  return val;
};
